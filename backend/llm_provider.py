"""
llm_provider.py — LLMProvider interface + GroqProvider + NoLLMProvider.

AI use disclosure: this file was generated with AI assistance and reviewed by the team.

Usage:
    from backend.llm_provider import get_provider
    provider = get_provider()
    interpretation = await provider.interpret(similarity_result_dict)

The Interpretation schema is defined in contracts/interpretation.schema.json.
ai_disclosure must match the exact string in that schema's const field.
"""

from __future__ import annotations

import json
import os
from abc import ABC, abstractmethod
from datetime import datetime, timezone

# ---------------------------------------------------------------------------
AI_DISCLOSURE = (
    "This interpretation was generated by an AI language model from measured data "
    "and scoring results. It has not been independently verified by domain scientists. "
    "Treat as a hypothesis, not a finding."
)

# ---------------------------------------------------------------------------


class LLMProvider(ABC):
    """Abstract base for LLM providers."""

    @abstractmethod
    async def interpret(self, result: dict) -> dict:
        """Generate an Interpretation dict from a SimilarityResult dict.

        Returns a dict matching contracts/interpretation.schema.json.
        """
        ...


# ---------------------------------------------------------------------------


class NoLLMProvider(LLMProvider):
    """Fallback provider — returns placeholder Interpretation without calling any LLM."""

    async def interpret(self, result: dict) -> dict:
        cell_id = result.get("cell_id", "unknown")
        target_id = result.get("target", {}).get("id", result.get("target_id", "unknown"))
        body = result.get("body", "unknown")
        mission_type = result.get("mission_type", "unknown")
        total = result.get("total_score", 0.0)
        tags = result.get("environment_tags", [])
        chars = result.get("selected_characteristics", [])

        tag_str = ", ".join(tags) if tags else "no environment tags"
        char_str = ", ".join(chars) if chars else "no characteristics selected"

        return {
            "cell_id": cell_id,
            "target_id": target_id,
            "body": body,
            "mission_type": mission_type,
            "model": "NoLLMProvider",
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "analog_summary": (
                f"LLM not configured. This cell (total score {total:.3f}) "
                f"was scored against target '{target_id}' using characteristics: "
                f"{char_str}. Environment tags: {tag_str}."
            ),
            "non_analog_summary": (
                "LLM not configured. Cannot reproduce on Earth: gravity, atmosphere, "
                "radiation, absolute temperatures, and regolith properties of the target body. "
                "See cannot_reproduce field in the SimilarityResult."
            ),
            "testable_activities": [
                "Terrain analogy testing (topography)",
                "Surface material and albedo comparison",
                "Thermal management hardware qualification",
                "Field navigation and EVA simulation",
            ],
            "confidence_note": (
                "LLM interpretation not available — GROQ_API_KEY not set. "
                f"Cell confidence level: {result.get('confidence', 'unknown')}. "
                "Some characteristic scores may use proxy or APPROXIMATE data; "
                "see characteristic_scores for per-variable confidence flags."
            ),
            "ai_disclosure": AI_DISCLOSURE,
        }


# ---------------------------------------------------------------------------


class GroqProvider(LLMProvider):
    """Calls the Groq API to generate a structured Interpretation.

    Reads GROQ_API_KEY and GROQ_MODEL from environment.
    Falls back to NoLLMProvider if the API call fails.
    """

    def __init__(self):
        self.api_key = os.environ.get("GROQ_API_KEY", "")
        self.model = os.environ.get("GROQ_MODEL", "llama-3.3-70b-versatile")
        self.api_url = "https://api.groq.com/openai/v1/chat/completions"

    async def interpret(self, result: dict) -> dict:
        import httpx  # optional import — only needed when LLM is configured

        cell_id = result.get("cell_id", "unknown")
        target = result.get("target", {})
        target_id = target.get("id", result.get("target_id", "unknown"))
        body = result.get("body", "unknown")
        mission_type = result.get("mission_type", "unknown")

        prompt = _build_prompt(result)

        payload = {
            "model": self.model,
            "messages": [
                {
                    "role": "system",
                    "content": (
                        "You are a planetary science analyst. Given scored Earth analog data, "
                        "produce a structured JSON interpretation following the exact schema provided. "
                        "Be concise, scientifically accurate, and explicit about limitations."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.3,
            "max_tokens": 800,
            "response_format": {"type": "json_object"},
        }

        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                response = await client.post(
                    self.api_url,
                    headers={"Authorization": f"Bearer {self.api_key}"},
                    json=payload,
                )
                response.raise_for_status()
                content = response.json()["choices"][0]["message"]["content"]
                parsed = json.loads(content)
        except Exception as exc:
            # Fall back to NoLLMProvider on any error
            fallback = NoLLMProvider()
            interp = await fallback.interpret(result)
            interp["confidence_note"] = (
                f"Groq API call failed: {exc}. "
                f"Original confidence: {result.get('confidence', 'unknown')}."
            )
            return interp

        # Enforce required fields and constant values
        now = datetime.now(timezone.utc).isoformat()
        return {
            "cell_id": cell_id,
            "target_id": target_id,
            "body": body,
            "mission_type": mission_type,
            "model": self.model,
            "generated_at": parsed.get("generated_at", now),
            "analog_summary": parsed.get("analog_summary", ""),
            "non_analog_summary": parsed.get("non_analog_summary", ""),
            "testable_activities": parsed.get("testable_activities", []),
            "characteristic_highlights": parsed.get("characteristic_highlights"),
            "confidence_note": parsed.get(
                "confidence_note",
                f"Cell confidence: {result.get('confidence', 'unknown')}.",
            ),
            "ai_disclosure": AI_DISCLOSURE,  # always overwrite with the canonical string
        }


# ---------------------------------------------------------------------------
# Prompt builder
# ---------------------------------------------------------------------------

def _build_prompt(result: dict) -> str:
    target = result.get("target", {})
    scores = result.get("characteristic_summary_scores", {})
    tags = result.get("environment_tags", [])
    cannot = result.get("cannot_reproduce", [])
    total = result.get("total_score", 0.0)
    conf = result.get("confidence", "unknown")

    scores_txt = "\n".join(f"  {k}: {v:.3f}" for k, v in scores.items())
    cannot_txt = "\n".join(f"  - {c}" for c in cannot[:4])
    tags_txt = ", ".join(tags) if tags else "none"

    return f"""Earth analog cell: {result.get("cell_id")}
Target: {target.get("name", target.get("id"))} ({result.get("body")}, {result.get("mission_type")})
Total score: {total:.3f}  |  Confidence: {conf}
Environment tags: {tags_txt}

Characteristic scores:
{scores_txt}

What Earth cannot reproduce:
{cannot_txt}

Produce JSON with these fields:
- analog_summary: ≤100 words — what this site analogs and why it matters for the mission
- non_analog_summary: ≤100 words — what it does NOT analog (gravity, atmosphere, temps, radiation, regolith)
- testable_activities: list of 2–5 short strings — activities that can be tested here
- confidence_note: ≤80 words — data limitations and confidence flags
(Do not include cell_id, target_id, model, generated_at, ai_disclosure — those are added automatically.)"""


# ---------------------------------------------------------------------------
# Factory
# ---------------------------------------------------------------------------

def get_provider() -> LLMProvider:
    """Return GroqProvider if GROQ_API_KEY is set, else NoLLMProvider."""
    if os.environ.get("GROQ_API_KEY"):
        return GroqProvider()
    return NoLLMProvider()
