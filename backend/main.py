"""
main.py — FastAPI application entry point for Planetary Twin AI.

AI use disclosure: this file was generated with AI assistance and reviewed by the team.

Start server:
    uvicorn backend.main:app --reload

Endpoints:
    GET  /characteristics
    GET  /missions
    GET  /candidates
    GET  /candidates/{cell_id}
    GET  /compare
    GET  /validation
    POST /interpret
"""

from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from backend.data_loader import load_earth_cells, load_targets
from backend.routers import (
    candidates,
    characteristics,
    compare,
    interpret,
    missions,
    validation,
)


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Load data files once at startup and store on app.state."""
    try:
        app.state.earth_df = load_earth_cells()
        print(f"[startup] Loaded {len(app.state.earth_df):,} Earth cells.")
    except FileNotFoundError as exc:
        # Allow server to start without data (tests use mock data)
        print(f"[startup] WARNING: {exc}")
        app.state.earth_df = None

    try:
        app.state.targets = load_targets()
        n = len(app.state.targets.get("targets", {}))
        print(f"[startup] Loaded {n} targets.")
    except FileNotFoundError as exc:
        print(f"[startup] WARNING: {exc}")
        app.state.targets = {"targets": {}}

    yield  # server is running


app = FastAPI(
    title="Planetary Twin AI",
    description=(
        "Score Earth locations as analogs for Moon and Mars mission sites. "
        "NASA Space Apps Challenge 2026 — Space Logistics team. "
        "AI use disclosure: scoring results are computed from open geospatial "
        "datasets; LLM interpretations are generated by an AI model and labeled as such."
    ),
    version="0.3.0",
    lifespan=lifespan,
)

# ---------------------------------------------------------------------------
# CORS — allow all origins for the static GitHub Pages frontend
# ---------------------------------------------------------------------------
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)

# ---------------------------------------------------------------------------
# Routers
# ---------------------------------------------------------------------------
app.include_router(characteristics.router)
app.include_router(missions.router)
app.include_router(candidates.router)
app.include_router(compare.router)
app.include_router(validation.router)
app.include_router(interpret.router)
